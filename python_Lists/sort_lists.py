# Sort List Alphanumerically
#  sort() - sorts alphanumerrically ascending

thislist = ["orange", "mango", "kiwi", "pineapple", "banana"]
thislist.sort()
print(thislist)

thislist = [100, 50, 65, 82, 23]
thislist.sort()
print(thislist)

# Sort descending
# reverse = true

thislist = [100, 50, 65, 82, 23]
thislist.sort(reverse= True)
print(thislist)
